"""Writes port/src/syms.js: every part's labels with their addresses, from each part's listing.json,
so that the port names the game's variables, tables and routines as the listing does. Run it again
after the listings change.  python3 port/scripts/syms.py"""
import json, os
GAME = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
PARTS = [('res', 'resident'), ('tit', 'title'), ('men', 'menu'), ('map', 'map'), ('bat', 'battle'), ('frt', 'fort'),
         ('trn', 'train'), ('end', 'ending')]
out = ['// Generated by port/scripts/syms.py from the parts\' listings: each part\'s labels and their',
       '// addresses (NSSyms.<part>.<label>). Do not edit; run the script again after the listings change.',
       '(function (root) {', "'use strict';", 'root.NSSyms = {']
for p, part in PARTS:
    L = json.load(open(os.path.join(GAME, 'parts', part, 'listing.json')))
    seen = {}
    for r in L['records']:
        if r.get('l') and r['l'] not in seen and not __import__('re').match(r'^[bjr]_[0-9A-F]{4}$', r['l']):
            seen[r['l']] = r['a']
    items = ', '.join('%s: 0x%04X' % (k, v) for k, v in seen.items())
    # wrapped at about 100 columns
    lines, cur = [], '    '
    for it in items.split(', '):
        if len(cur) + len(it) + 2 > 104:
            lines.append(cur.rstrip())
            cur = '    '
        cur += it + ', '
    lines.append(cur.rstrip().rstrip(','))
    out.append('  %s: {' % p)
    out.extend(lines)
    out.append('  },')
out += ['};', "})(typeof window !== 'undefined' ? window : globalThis);", '']
open(os.path.join(GAME, 'port', 'src', 'syms.js'), 'w').write('\n'.join(out))
print('wrote port/src/syms.js')
